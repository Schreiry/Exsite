/**
 * Оплата: куда ведёт кнопка «Купить».
 *
 * Деньги принимает посредник (Lemon Squeezy): он сам продавец, сам платит
 * налоги и сам делает выплату на счёт. Своего приёма карт у нас нет и не
 * планируется — это лицензии, банки и ответственность, которых семейному делу
 * не нужно.
 *
 * После оплаты посредник стучится в нашу службу активации
 * (`/webhook/payment`), она выдаёт свободный ключ нужного издания из пула и
 * отправляет письмо. Владельцу приходит уведомление. Всё это происходит без
 * участия человека — покупка ночью не ждёт утра.
 *
 * ЧТО НУЖНО СДЕЛАТЬ ОДИН РАЗ (подробно — в README):
 *   1. Завести магазин на lemonsqueezy.com и четыре товара с названиями,
 *      содержащими слова Essential / Standart / Advanced / Ultimate —
 *      по названию служба и понимает, какое издание выдавать.
 *   2. Скопировать ссылку оплаты каждого товара в `CHECKOUT_URLS` ниже.
 *   3. В настройках магазина указать вебхук на адрес службы + `/webhook/payment`
 *      и записать его секрет в переменную `PAYMENT_WEBHOOK_SECRET` службы.
 *
 * Пока ссылок нет, кнопка «Купить» ведёт на форму заявки — покупатель не
 * упирается в тупик, а вы получаете письмо и выдаёте ключ вручную.
 */
import type { EditionId } from './editions';

export const CHECKOUT_URLS: Record<EditionId, string> = {
	essential: '',
	standart: '',
	advanced: '',
	ultimate: '',
};

/** Готова ли оплата хотя бы для одного издания. */
export const paymentReady = (): boolean =>
	Object.values(CHECKOUT_URLS).some((u) => u.trim().length > 0);

/** Куда вести с кнопки покупки: на оплату или на заявку. */
export function checkoutFor(id: EditionId): string | null {
	const url = CHECKOUT_URLS[id]?.trim();
	return url ? url : null;
}
