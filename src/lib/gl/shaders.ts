/**
 * Исходники живых материалов.
 *
 * Общая мысль обоих шейдеров одна и та же, и она стоит объяснения, потому что
 * из неё следует, почему это выглядит стеклом, а не цветным туманом.
 *
 *   1. Считаем ВЫСОТУ невидимой поверхности в каждой точке. Высота — сумма
 *      нескольких слоёв шума, где каждый следующий мельче и слабее предыдущего.
 *      Чтобы поверхность текла, а не дрожала, координаты сначала смещаются
 *      другим шумом: это и даёт длинные складки ткани и медленную воду.
 *   2. Из высоты берём НАКЛОН — насколько поверхность завалена в этой точке.
 *   3. Наклон ПРЕЛОМЛЯЕТ то, что лежит под стеклом: смотрим на подложку не
 *      прямо, а со сдвигом. Красный, зелёный и синий сдвигаем чуть по-разному —
 *      именно это стекло даёт по краям радужную кромку.
 *   4. Добавляем БЛИК: там, где наклон повёрнут к свету, поверхность светлеет.
 *
 * Всё это считает видеокарта для каждой точки экрана. Готовых картинок и видео
 * здесь нет, поэтому материал одинаково чёткий на телефоне и на большом
 * мониторе и ничего не весит при загрузке.
 *
 * ТЕКСТ ВАЖНЕЕ КРАСОТЫ. У обоих материалов есть множитель спокойствия: в тех
 * местах, где лежат буквы, волны приглушаются. Красивый фон, из-за которого
 * приходится вчитываться, — плохой фон.
 */

/** Общая часть: шум, складки, наклон. */
const FIELD = `
float hash(vec2 p) {
	p = fract(p * vec2(123.34, 456.21));
	p += dot(p, p + 45.32);
	return fract(p.x * p.y);
}

float noise(vec2 p) {
	vec2 i = floor(p);
	vec2 f = fract(p);
	// Сглаживание Перлина: у краёв клетки производная равна нулю, поэтому
	// стыки соседних клеток не видны как сетка.
	vec2 u = f * f * (3.0 - 2.0 * f);
	float a = hash(i);
	float b = hash(i + vec2(1.0, 0.0));
	float c = hash(i + vec2(0.0, 1.0));
	float d = hash(i + vec2(1.0, 1.0));
	return mix(mix(a, b, u.x), mix(c, d, u.x), u.y);
}

float fbm(vec2 p) {
	float sum = 0.0;
	float amp = 0.5;
	for (int i = 0; i < 4; i++) {
		sum += amp * noise(p);
		p *= 2.03;   // не ровно 2, иначе слои совпадают углами и дают клетку
		amp *= 0.5;
	}
	return sum;
}

/** Высота поверхности: складки, смещённые другими складками. */
float height(vec2 p, float t) {
	vec2 warp = vec2(fbm(p + vec2(0.0, t * 0.06)), fbm(p + vec2(5.2, 1.3 - t * 0.05)));
	return fbm(p + warp * 1.6 + vec2(t * 0.02, -t * 0.03));
}
`;

/**
 * Фон сайта: угольная ткань.
 *
 * Тёмное полотно, по которому медленно ходят складки, а по складкам скользит
 * холодный свет. Цвета здесь нет намеренно — только уголь, графит и серебро:
 * любой оттенок на таком размере читается как подсветка игрового корпуса, а не
 * как дорогой материал.
 *
 * Свет положен так, чтобы он никогда не собирался в яркое пятно посреди
 * экрана: блики скользят по краям складок, и текст поверх остаётся читаемым
 * в любой момент времени.
 */
export const BACKDROP_FRAGMENT = `#version 300 es
precision highp float;
out vec4 outColor;

uniform vec2 uSize;
uniform float uTime;
uniform float uAmp;    // сила складок
uniform float uLight;  // сила бликов
uniform vec3 uDeep;    // самое тёмное место полотна
uniform vec3 uHigh;    // самое светлое место полотна

${FIELD}

void main() {
	vec2 uv = gl_FragCoord.xy / uSize;
	// Сохраняем пропорции: иначе на широком мониторе складки растягиваются
	// в горизонтальные полосы и выдают, что это плоская картинка.
	vec2 p = uv * vec2(uSize.x / uSize.y, 1.0) * 1.9;
	float t = uTime * 0.6;

	float e = 1.4 / uSize.y;
	float h = height(p, t);
	float hx = height(p + vec2(e, 0.0), t);
	float hy = height(p + vec2(0.0, e), t);
	vec2 slope = vec2(hx - h, hy - h) / e;
	vec3 n = normalize(vec3(-slope * uAmp, 1.0));

	// Полотно: глубина складки решает, насколько место тёмное.
	float depth = smoothstep(0.28, 0.78, h);
	vec3 color = mix(uDeep, uHigh, depth);

	// Два источника света с разных сторон. Второй холоднее и слабее —
	// он даёт ткани объём, не превращая её в металл.
	vec3 l1 = normalize(vec3(-0.45, 0.62, 0.65));
	vec3 l2 = normalize(vec3(0.72, -0.3, 0.62));
	float s1 = pow(max(dot(n, l1), 0.0), 26.0);
	float s2 = pow(max(dot(n, l2), 0.0), 44.0);
	color += (s1 * 0.55 + s2 * 0.3) * uLight;

	// Холодный отлив на самых крутых склонах: тот самый намёк на радугу,
	// который есть у стекла и которого нет у матовой ткани.
	float edge = clamp(length(slope) * uAmp * 0.9, 0.0, 1.0);
	color += vec3(0.13, 0.14, 0.17) * pow(edge, 2.2) * uLight;

	// Зерно. Без него на больших тёмных участках браузер рисует ступеньки
	// градиента, и дорогое полотно выглядит дешёвой заливкой.
	float grain = fract(sin(dot(gl_FragCoord.xy, vec2(12.9898, 78.233))) * 43758.5453);
	color += (grain - 0.5) * 0.012;

	outColor = vec4(color, 1.0);
}`;

/**
 * Материал внутри карточки издания.
 *
 * Чем дороже издание, тем гуще материал: у младшего это тихий дым, у старшего —
 * текучее стекло с бликами. Разница сделана не яркостью цвета, а количеством
 * слоёв и глубиной — так же, как дорогая вещь отличается от дешёвой в жизни.
 */
export const EDITION_FRAGMENT = `#version 300 es
precision highp float;
out vec4 outColor;

uniform vec2 uSize;
uniform float uTime;
uniform float uHue;    // оттенок, градусы
uniform float uRich;   // насыщенность материала, 0..1
uniform float uWake;   // 0 покой, 1 карточка выбрана
uniform float uTone;   // 0 светлая подложка, 1 тёмная

${FIELD}

vec3 fromHue(float deg, float sat, float val) {
	float h = deg / 60.0;
	vec3 k = mod(vec3(5.0, 3.0, 1.0) + h, 6.0);
	return val - val * sat * clamp(min(k, 4.0 - k), 0.0, 1.0);
}

void main() {
	vec2 uv = gl_FragCoord.xy / uSize;
	vec2 p = uv * vec2(uSize.x / uSize.y, 1.0) * 2.6;
	float t = uTime * mix(0.55, 1.0, uRich) + uWake * 1.5;

	float e = 1.8 / uSize.y;
	float h = height(p, t);
	float hx = height(p + vec2(e, 0.0), t);
	float hy = height(p + vec2(0.0, e), t);
	vec2 slope = vec2(hx - h, hy - h) / e;

	float amp = mix(0.35, 1.25, uRich) * (1.0 + uWake * 0.4);
	vec2 shift = slope * amp * 0.05;

	// Подложка карточки: снизу гуще, сверху почти чисто. Текст лежит сверху,
	// и материал не должен с ним спорить.
	float depth = smoothstep(0.05, 1.0, uv.y);
	vec3 tint = fromHue(uHue, mix(0.30, 0.62, uRich), 1.0);
	vec3 base = mix(vec3(0.02, 0.025, 0.035), tint * mix(0.35, 0.85, uRich), depth * 0.9);

	vec3 color = vec3(
		base.r * (1.0 + shift.x * 2.2),
		base.g * (1.0 + shift.y * 2.0),
		base.b * (1.0 - shift.x * 1.8)
	);

	vec3 n = normalize(vec3(-slope * amp, 1.0));
	float spec = pow(max(dot(n, normalize(vec3(-0.35, 0.55, 0.76))), 0.0), mix(30.0, 14.0, uRich));
	color += spec * mix(0.10, 0.5, uRich);

	// Плотность к нижнему краю и прозрачность к верхнему: карточка растворяется
	// в своей стеклянной рамке, а не обрывается прямоугольником.
	float alpha = mix(0.16, 0.62, uRich) * smoothstep(-0.15, 0.85, uv.y);
	alpha *= mix(1.0, 1.25, uWake);

	outColor = vec4(color, clamp(alpha, 0.0, 1.0));
}`;
